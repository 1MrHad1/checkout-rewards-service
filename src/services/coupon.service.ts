import { randomUUID } from 'node:crypto';
import { config } from '../config.js';
import { pool, withTransaction, isUniqueViolation } from '../db/pool.js';
import { AppError } from '../domain/errors.js';

export interface CouponView {
  code: string;
  milestoneIndex: number;
  percentOff: number;
  status: 'available' | 'redeemed';
  orderId: string | null;
  createdAt: string;
  redeemedAt: string | null;
}

/**
 * Milestone arithmetic.
 *
 * Milestone k is reached once k * interval orders have been placed. The number
 * of milestones *earned* is therefore floor(totalOrders / interval), and the
 * next one to reward is the lowest earned milestone that has no coupon yet.
 *
 * Deriving this from a live COUNT of orders rather than from an order sequence
 * number is deliberate: a rolled-back checkout consumes a sequence value, so
 * sequence-based counting would silently skip milestones. See DECISIONS.md.
 */
export function nextUnrewardedMilestone(
  totalOrders: number,
  rewardedMilestones: readonly number[],
  interval: number,
): number | null {
  const earned = Math.floor(totalOrders / interval);
  const rewarded = new Set(rewardedMilestones);

  for (let milestone = 1; milestone <= earned; milestone += 1) {
    if (!rewarded.has(milestone)) return milestone;
  }
  return null;
}

const generateCode = (milestone: number): string =>
  `SAVE${config.rewards.percentOff}-M${milestone}-${randomUUID().slice(0, 8).toUpperCase()}`;

/**
 * Administrative: mints a coupon for the next unrewarded milestone.
 *
 * Two admins clicking at the same moment both compute the same milestone. The
 * UNIQUE constraint on `milestone_index` is what makes exactly one of them win;
 * the loser is told the milestone was already rewarded rather than being handed
 * a duplicate coupon.
 */
export async function generateCoupon(): Promise<CouponView> {
  return withTransaction(async (client) => {
    const [{ rows: orderRows }, { rows: couponRows }] = await Promise.all([
      client.query<{ count: number }>('SELECT COUNT(*)::int AS count FROM orders'),
      client.query<{ milestone_index: number }>('SELECT milestone_index FROM coupons'),
    ]);

    const totalOrders = orderRows[0]!.count;
    const rewarded = couponRows.map((row) => row.milestone_index);
    const milestone = nextUnrewardedMilestone(totalOrders, rewarded, config.rewards.orderInterval);

    if (milestone === null) {
      const earned = Math.floor(totalOrders / config.rewards.orderInterval);
      const ordersUntilNext = config.rewards.orderInterval * (earned + 1) - totalOrders;
      throw new AppError(
        'MILESTONE_NOT_REACHED',
        `No unrewarded milestone is available. ${ordersUntilNext} more order(s) needed.`,
        {
          totalOrders,
          orderInterval: config.rewards.orderInterval,
          milestonesRewarded: rewarded.length,
          ordersUntilNextMilestone: ordersUntilNext,
        },
      );
    }

    try {
      const result = await client.query<CouponRow>(
        `INSERT INTO coupons (code, milestone_index, percent_off)
         VALUES ($1, $2, $3)
         RETURNING code, milestone_index, percent_off, status, order_id, created_at, redeemed_at`,
        [generateCode(milestone), milestone, config.rewards.percentOff],
      );
      return toCouponView(result.rows[0]!);
    } catch (error) {
      if (isUniqueViolation(error)) {
        throw new AppError(
          'MILESTONE_ALREADY_REWARDED',
          `A coupon for milestone ${milestone} was generated by a concurrent request`,
          { milestoneIndex: milestone },
        );
      }
      throw error;
    }
  });
}

export async function listCoupons(): Promise<CouponView[]> {
  const result = await pool.query<CouponRow>(
    `SELECT code, milestone_index, percent_off, status, order_id, created_at, redeemed_at
       FROM coupons
      ORDER BY milestone_index`,
  );
  return result.rows.map(toCouponView);
}

export interface CouponRow {
  code: string;
  milestone_index: number;
  percent_off: number;
  status: 'available' | 'redeemed';
  order_id: string | null;
  created_at: Date;
  redeemed_at: Date | null;
}

export const toCouponView = (row: CouponRow): CouponView => ({
  code: row.code,
  milestoneIndex: row.milestone_index,
  percentOff: row.percent_off,
  status: row.status,
  orderId: row.order_id,
  createdAt: row.created_at.toISOString(),
  redeemedAt: row.redeemed_at ? row.redeemed_at.toISOString() : null,
});
